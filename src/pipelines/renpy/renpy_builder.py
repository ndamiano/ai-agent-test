EXAMPLE_DEFINITION = {
    "title": "A Short Story",
    "output_dir": "example_game",
    "characters": [
        {"id": "alice", "name": "Alice", "color": "#c8ffc8"},
        {"id": "bob",   "name": "Bob",   "color": "#c8c8ff"},
    ],
    "images": [
        {"id": "bg forest", "file": "forest.jpg"},
        {"id": "bg town",   "file": "town.jpg"},
    ],
    "scenes": [
        {
            "background": "bg forest",
            "lines": [
                {"who": None,    "say": "Deep in the forest, two friends met."},
                {"who": "alice", "say": "Bob! I've been looking for you."},
                {"who": "bob",   "say": "Alice... we need to talk."},
            ]
        },
        {
            "background": "bg town",
            "lines": [
                {"who": None,    "say": "They walked back to town together."},
                {"who": "alice", "say": "Whatever happens, we face it together."},
                {"who": "bob",   "say": "Together, then."},
            ]
        }
    ]
}


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Build a RenPy game from a JSON definition.")
    parser.add_argument("definition", nargs="?", help="Path to game definition JSON file. Omit to run built-in example.")
    parser.add_argument("--sdk",      help="Path to RenPy SDK root (overrides RENPY_SDK env var)")
    parser.add_argument("--out",      help="Output directory (overrides output_dir in definition)")
    parser.add_argument("--no-dist",  action="store_true", help="Write project files only; skip distribution build")
    args = parser.parse_args()

    if args.definition:
        with open(args.definition) as f:
            definition = json.load(f)
    else:
        print("[renpy_builder] No definition file provided — running built-in example.")
        definition = EXAMPLE_DEFINITION

    build_game(
        definition,
        output_dir=args.out,
        sdk_path=args.sdk,
        distribute=not args.no_dist,
    )